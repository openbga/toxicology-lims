#!/usr/bin/env python3
"""Generate CHANGELOG.md and the What's new list from changelog.d/ (Python 3.11+, stdlib only).

Each change that users, deployers or integrators can observe adds one entry file,
`changelog.d/YYYY-MM-DD-short-slug.md`: flat `key: value` front matter between `---` lines, a
plain summary and an optional `## Technical notes` section. See
.ai/skills/changelog-entry/SKILL.md for when and how to write one.

  (no option)         Write CHANGELOG.md and the application's bundled list.
  --bundle            Write only the bundled list; npm runs this before dev, build, typecheck,
                      test and knip. The list is not tracked, so branches never conflict on it.
  --check             Exit 1 when an entry is invalid.
  --release X.Y.Z     Stamp `release: X.Y.Z` on every entry without a release, then write.
  --require-release   With --check: every entry must carry a release and CHANGELOG.md must be
                      current (pull requests into main). CHANGELOG.md is tracked and changes
                      only when a release is cut, so branches do not conflict on it either.

Entries without a release form the Unreleased group on top; releases follow, newest first
(docs/development/releases.md#cut-a-release).
"""

import argparse
from datetime import date as Date
import json
from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parent.parent
ENTRIES = "changelog.d"
DOCUMENT = "CHANGELOG.md"
BUNDLE = "ui/src/features/whats-new/changelog.json"
PULL_URL = "https://github.com/openbga/toxicology-lims/pull/"

TYPES = ("added", "changed", "fixed", "removed", "deprecated", "security")
IMPACTS = ("high", "medium", "low")
REQUIRED = ("date", "type", "impact", "title")
OPTIONAL = ("area", "link", "pr", "release")
FILE_NAME = re.compile(r"\d{4}-\d{2}-\d{2}-[a-z0-9]+(?:-[a-z0-9]+)*\.md")
ISO_DATE = re.compile(r"\d{4}-\d{2}-\d{2}")
RELEASE = re.compile(r"(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)")
NOTES_HEADING = "## Technical notes"
HEADER = (
    "<!-- Generated by scripts/changelog.py from changelog.d/. Do not edit this file by hand:\n"
    "     add or change an entry in changelog.d/, then run `python3 scripts/changelog.py`. -->\n"
)


class EntryError(Exception):
    pass


def parse_entry(name, text):
    """One entry file as a dict; raises EntryError naming the file and the problem."""

    def fail(problem):
        raise EntryError(f"{ENTRIES}/{name}: {problem}")

    if not FILE_NAME.fullmatch(name):
        fail("the file name must be YYYY-MM-DD-short-slug.md (lowercase letters, digits, hyphens)")
    lines = text.replace("\r\n", "\n").split("\n")
    if lines[0] != "---" or "---" not in lines[1:]:
        fail("the file must start with front matter between two '---' lines")
    end = lines.index("---", 1)
    entry = {"id": name.removesuffix(".md")}
    for line in lines[1:end]:
        key, separator, value = line.partition(":")
        key, value = key.strip(), value.strip()
        if not separator or not key:
            fail(f"front matter line {line!r} is not 'key: value'")
        if key not in REQUIRED + OPTIONAL:
            fail(f"unknown key '{key}'")
        if key in entry:
            fail(f"key '{key}' appears twice")
        if not value:
            fail(f"key '{key}' has no value")
        entry[key] = value
    for key in REQUIRED:
        if key not in entry:
            fail(f"missing required key '{key}'")
    if not ISO_DATE.fullmatch(entry["date"]):
        fail(f"key 'date' must be YYYY-MM-DD, not {entry['date']!r}")
    try:
        Date.fromisoformat(entry["date"])
    except ValueError:
        fail(f"key 'date' is not a calendar date: {entry['date']!r}")
    if entry["type"] not in TYPES:
        fail(f"key 'type' must be one of {', '.join(TYPES)}, not {entry['type']!r}")
    if entry["impact"] not in IMPACTS:
        fail(f"key 'impact' must be one of {', '.join(IMPACTS)}, not {entry['impact']!r}")
    if entry["title"].endswith("."):
        fail("key 'title' must not end with a period")
    if "link" in entry and not entry["link"].startswith("/"):
        fail(f"key 'link' must be an application path starting with '/', not {entry['link']!r}")
    if "pr" in entry:
        if not entry["pr"].isdigit() or int(entry["pr"]) == 0:
            fail(f"key 'pr' must be a pull request number, not {entry['pr']!r}")
        entry["pr"] = int(entry["pr"])
    if "release" in entry and not RELEASE.fullmatch(entry["release"]):
        fail(f"key 'release' must be a version such as 0.2.0, not {entry['release']!r}")
    body = "\n".join(lines[end + 1 :])
    summary, heading, notes = body.partition(f"\n{NOTES_HEADING}\n")
    if not heading and body.startswith(f"{NOTES_HEADING}\n"):
        summary, notes, heading = "", body.removeprefix(f"{NOTES_HEADING}\n"), NOTES_HEADING
    entry["summary"] = summary.strip()
    if not entry["summary"]:
        fail("the summary before '## Technical notes' is empty")
    if "\n#" in f"\n{entry['summary']}":
        fail("the summary must not contain headings; use '## Technical notes' for details")
    if heading:
        entry["notes"] = notes.strip()
        if not entry["notes"]:
            fail("'## Technical notes' is empty; remove the heading or add the notes")
    return entry


def read_entries(root):
    folder = root / ENTRIES
    if not folder.is_dir():
        return []
    entries, errors = [], []
    for path in sorted(folder.iterdir()):
        if path.name.startswith(".") or path.name == "README.md":
            continue
        try:
            entries.append(parse_entry(path.name, path.read_text(encoding="utf-8")))
        except EntryError as error:
            errors.append(str(error))
    if errors:
        raise EntryError("\n".join(errors))
    return entries


def version_key(release):
    return tuple(int(part) for part in release.split("."))


def groups(entries):
    """Unreleased first, then releases newest first; inside, by impact, newest first, then title."""
    releases = {entry.get("release") for entry in entries}
    ordered = [None] if None in releases else []
    ordered += sorted(releases - {None}, key=version_key, reverse=True)
    result = []
    for release in ordered:
        members = [entry for entry in entries if entry.get("release") == release]
        dates = [entry["date"] for entry in members]
        impacts = []
        for impact in IMPACTS:
            chosen = [entry for entry in members if entry["impact"] == impact]
            chosen.sort(key=lambda entry: entry["title"].casefold())
            chosen.sort(key=lambda entry: entry["date"], reverse=True)
            if chosen:
                impacts.append({"impact": impact, "entries": chosen})
        result.append({"release": release, "from": min(dates), "to": max(dates), "impacts": impacts})
    return result


def date_range(group):
    return group["from"] if group["from"] == group["to"] else f"{group['from']} to {group['to']}"


def indent(text):
    return "\n".join(f"  {line}" if line else "" for line in text.split("\n"))


def render_document(grouped):
    out = [
        HEADER,
        "# Changelog\n",
        "What changed in OpenBGA Toxicology LIMS, newest release first. Changes not yet in a",
        "release are listed under Unreleased. Within a release, changes are ordered by impact, then",
        "newest first. The application shows the same list under **What's new**.\n",
    ]
    if not grouped:
        out.append("No changes are recorded yet.\n")
    for group in grouped:
        name = group["release"] or "Unreleased"
        out.append(f"## {name} ({date_range(group)})\n")
        for impact in group["impacts"]:
            out.append(f"### {impact['impact'].capitalize()} impact\n")
            for entry in impact["entries"]:
                line = f"- **{entry['type'].capitalize()}:** {entry['title']} ({entry['date']}"
                if "pr" in entry:
                    line += f", [#{entry['pr']}]({PULL_URL}{entry['pr']})"
                out.append(line + ")\n")
                out.append(indent(entry["summary"]) + "\n")
                if "notes" in entry:
                    out.append("  Technical notes:\n")
                    out.append(indent(entry["notes"]) + "\n")
    return "\n".join(out).rstrip("\n") + "\n"


def render_bundle(grouped):
    return json.dumps({"groups": grouped}, indent=2, ensure_ascii=False) + "\n"


def outputs(root):
    grouped = groups(read_entries(root))
    return {DOCUMENT: render_document(grouped), BUNDLE: render_bundle(grouped)}


def stamp_release(root, release):
    """Add `release: <release>` to each entry without one; returns the stamped file names."""
    if not RELEASE.fullmatch(release):
        raise EntryError(f"{release!r} is not a release version such as 0.2.0")
    stamped = []
    for entry in read_entries(root):
        if "release" in entry:
            continue
        path = root / ENTRIES / f"{entry['id']}.md"
        lines = path.read_text(encoding="utf-8").split("\n")
        end = lines.index("---", 1)
        lines.insert(end, f"release: {release}")
        path.write_text("\n".join(lines), encoding="utf-8")
        stamped.append(path.name)
    return stamped


def main(argv=None, root=ROOT):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--bundle", action="store_true")
    mode.add_argument("--release", metavar="X.Y.Z")
    parser.add_argument("--require-release", action="store_true")
    args = parser.parse_args(argv)
    if args.require_release and not args.check:
        parser.error("--require-release is used with --check")
    try:
        if args.release:
            for name in stamp_release(root, args.release):
                print(f"Stamped {ENTRIES}/{name} with release {args.release}")
        files = outputs(root)
        if args.require_release:
            missing = [entry["id"] for entry in read_entries(root) if "release" not in entry]
            if missing:
                raise EntryError(
                    "These entries have no release; stamp them with "
                    "`python3 scripts/changelog.py --release X.Y.Z`:\n  " + "\n  ".join(missing)
                )
    except EntryError as error:
        print(error, file=sys.stderr)
        return 1
    if args.check:
        document = root / DOCUMENT
        if args.require_release and (
            not document.is_file() or document.read_text(encoding="utf-8") != files[DOCUMENT]
        ):
            print(
                f"{DOCUMENT} is out of date. Run `python3 scripts/changelog.py` and commit the result.",
                file=sys.stderr,
            )
            return 1
        return 0
    if args.bundle:
        files = {BUNDLE: files[BUNDLE]}
    for name, text in files.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
            print(f"Wrote {name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
